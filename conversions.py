#Convert Boolean to Integer
value = True
result1 = int(value)
print("Integer Value =", result1)

#Convert Float to String
num = 45.67
result2 = str(num)
print("String Value =", result2)

#Convert 20°C to Fahrenheit
celsius = 20
fahrenheit = (9/5 * celsius) + 32
print("Fahrenheit =", fahrenheit)

#Convert 50°F to Celsius
fahrenheit2 = 50
celsius2 = (5/9) * (fahrenheit2 - 32)
print("Celsius =", celsius2)

# Convert Integer to Binary
number = 25
binary_value = bin(number)
print("Binary Value =", binary_value)
