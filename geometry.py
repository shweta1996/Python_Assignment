# Calculate Area of a Triangle
base = 10
height = 6
area = (base * height) / 2
print("Area of Triangle =", area)

# Calculate Perimeter of a Square
side = 9
perimeter = 4 * side
print("Perimeter of Square =", perimeter)

# Calculate Diameter of a Circle
radius = 14
diameter = 2 * radius
print("Diameter of Circle =", diameter)

# Calculate Volume of a Cube
side_cube = 5
volume = side_cube ** 3
print("Volume of Cube =", volume)

# Calculate Surface Area of a Cuboid
l = 4
b = 3
h = 2
surface_area = 2 * (l*b + b*h + l*h)
print("Surface Area of Cuboid =", surface_area)