# 5. Update balance after deposit 
# Initial balance: current_balance = 10000, Deposit amount: deposit_balance = 5000 
# Output: ○ Before deposit: current_balance = 10000 ○ After deposit: current_balance = 15000
current_balance = 10000
deposit_balance=5000
print("Before deposit: current_balance = ", current_balance)
print("After deposit: current_balance = ", current_balance+deposit_balance)